/*
 * Which kanji may appear as CARDS or INTENTS (GUIDELINE §4–5).
 * The Kanken pools are fixed per depth — that is the point of the game — but not every kanji in a
 * grade is playable: some exist in the grade only as place-name components, some are bare radicals.
 *
 *  STAGE_ONLY_KANJI  the 2020 prefecture additions that have no life outside a place name.
 *                    They may NAME a stage (茨城, 新潟 …) but never show up in a hand or as an intent.
 *  CARD_EXCLUDE      radical / component shapes in the 1級 pool with no standalone meaning.
 *  PLAYABLE_POOLS    optional curated whitelist per depth, loaded from /kanken_curated.json when it
 *                    exists (see GUIDELINE §5 — generated by a cheap model, never by hand).
 */
const STAGE_ONLY_KANJI = new Set([..."茨媛潟岐埼滋栃奈阪阜"]);
const CARD_EXCLUDE = new Set([..."丿儿气亅厶丶彳乂厂广弋幺夂彡亠勹冂宀韋冖廾癶殳夬攵兀冫聿卩帚凵咼从髟毋屮戉廴旡尢巛豸襾齊攴艸夊匸黹弖爿耒爻"]);
let PLAYABLE_POOLS = {};

function isPlayableKanji(k) {
  const s = String(k || "");
  if (!s) return false;
  if ([...s].length !== 1) return true;              // fused cards (2 kanji) are player-made, always allowed
  return !STAGE_ONLY_KANJI.has(s) && !CARD_EXCLUDE.has(s);
}

/* The depth's pool as cards may be drawn from it. */
function playableDepthPool(depthId) {
  const base = PLAYABLE_POOLS[depthId] || ((KANKEN_DATA[depthId] && KANKEN_DATA[depthId].kanji) || []);
  return base.filter(isPlayableKanji);
}
