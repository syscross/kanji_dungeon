function t(key) {
  const pack = I18N[config.lang] || I18N.EN;
  return pack[key] || I18N.EN[key] || key;
}

function applyLocalization() {
  document.getElementById("lang-current-label").textContent = `🌐 ${config.lang} ▾`;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.getAttribute("data-i18n");
    const val = t(k);
    if (typeof val === "string") el.textContent = val;
  });
  const inp = document.getElementById("b-input");
  if (inp) inp.placeholder = t("inputPlaceholder");
  document.getElementById("mode-badge").textContent = `${t("mode")}: ${config.instMode}`;
}
